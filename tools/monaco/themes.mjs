import { mkdir, readFile, writeFile } from 'node:fs/promises';

const source = new URL('./node_modules/tm-themes/', import.meta.url);
const dest = new URL('../../vendor/themes/', import.meta.url);
const inputs = [
  ['light', 'Light+', 'light-plus'], ['dark', 'Dark+', 'dark-plus'],
  ['one-dark', 'One Dark', 'one-dark-pro'], ['dracula', 'Dracula', 'dracula'],
  ['monokai', 'Monokai', 'monokai'], ['nord', 'Nord', 'nord'],
  ['github-dark', 'GitHub Dark', 'github-dark'], ['tokyo-night', 'Tokyo Night', 'tokyo-night'],
];
const scopes = { comment: 'comment.line', string: 'string.quoted.double', 'string.escape': 'constant.character.escape',
  number: 'constant.numeric', keyword: 'keyword.control', 'keyword.directive': 'keyword.control.directive',
  type: 'storage.type', 'type.identifier': 'entity.name.type', identifier: 'variable.other.readwrite',
  operator: 'keyword.operator', delimiter: 'punctuation.separator', regexp: 'string.regexp' };

// Monarch uses short token IDs. Select the most specific matching TextMate scope,
// preserving separate foreground and font-style overrides in upstream order.
function ruleFor(token, target, entries) {
  const found = {};
  const scores = {};
  for (const { scope, settings } of entries) {
    for (const name of (Array.isArray(scope) ? scope : [scope || '']).flatMap(s => s.split(',').map(v => v.trim()))) {
      if (!name || target !== name && !target.startsWith(name + '.')) continue;
      for (const key of ['foreground', 'fontStyle']) {
        if (typeof settings[key] === 'string' && name.length >= (scores[key] || 0)) {
          scores[key] = name.length;
          found[key] = key === 'foreground' ? settings[key].slice(1, 7) : settings[key];
        }
      }
    }
  }
  return { token, ...found };
}

function luminance(rgb) {
  const linear = rgb.map(v => v <= 10 ? v / 3294.6 : ((v / 255 + 0.055) / 1.055) ** 2.4);
  return linear[0] * 0.2126 + linear[1] * 0.7152 + linear[2] * 0.0722;
}
function readable(color, backgrounds, dark) {
  const rgb = value => value.slice(1, 7).match(/../g).map(v => parseInt(v, 16));
  const original = rgb(color), surfaces = backgrounds.map(bg => luminance(rgb(bg)));
  for (let step = 0; step <= 20; step++) {
    const adjusted = original.map(v => Math.round(v + ((dark ? 255 : 0) - v) * step / 20));
    const lum = luminance(adjusted);
    if (surfaces.every(bg => (Math.max(lum, bg) + 0.05) / (Math.min(lum, bg) + 0.05) >= 4.5))
      return '#' + adjusted.map(v => v.toString(16).padStart(2, '0')).join('');
  }
  return dark ? '#ffffff' : '#000000';
}

const definitions = {}, palettes = {};
for (const [id, label, file] of inputs) {
  const t = JSON.parse(await readFile(new URL('themes/' + file + '.json', source), 'utf8'));
  const c = t.colors, dark = t.type === 'dark';
  const base = c['editor.background'], ink = c['editor.foreground'];
  const surface = c['sideBar.background'] || c['editorWidget.background'] || (dark ? '#252526' : '#f3f3f3');
  const accent = c['textLink.foreground'] || c['terminal.ansiBrightBlue'] || (dark ? '#75beff' : '#006ab1');
  const muted = c.descriptionForeground || c['editorLineNumber.foreground'] || ink;
  const border = c['panel.border'] || c['editorGroup.border'] || (dark ? '#454545' : '#d4d4d4');
  const red = c['editorError.foreground'] || (dark ? '#f48771' : '#a1260d');
  const green = dark ? (c['terminal.ansiBrightGreen'] || '#89d185') : '#19703b';
  const amber = dark ? (c['terminal.ansiBrightYellow'] || '#cca700') : '#805900';
  palettes[id] = { label, dark, base, ink, surface, muted, border, accent, red, green, amber };
  for (const key of ['accent', 'red', 'green', 'amber']) {
    palettes[id][key] = readable(palettes[id][key], [base, surface], dark);
  }
  const colors = Object.fromEntries(Object.entries(c).filter(([k, v]) =>
    /^(editor|list\.|menu\.|input\.|scrollbar|symbolIcon|breadcrumb|focusBorder|contrastBorder)/.test(k) && /^#[a-f\d]{3,8}$/i.test(v)));
  Object.assign(colors, {
    'editorWidget.background': c['editorWidget.background'] || surface,
    'editorSuggestWidget.background': c['editorSuggestWidget.background'] || surface,
    'editorStickyScroll.background': c['editorStickyScroll.background'] || base,
    'editor.wordHighlightBackground': accent.slice(0, 7) + '42', 'editor.wordHighlightStrongBackground': accent.slice(0, 7) + '60',
    'editor.wordHighlightTextBackground': '#00000000', 'editor.wordHighlightTextBorder': accent.slice(0, 7) + 'a0',
  });
  const rules = Object.entries(scopes).map(([token, target]) => ruleFor(token, target, t.tokenColors)).filter(r => Object.keys(r).length > 1);
  definitions[id] = { base: dark ? 'vs-dark' : 'vs', inherit: true, rules, colors };
}
await mkdir(dest, { recursive: true });
const generated = '// Generated by tools/monaco/themes.mjs from the locked tm-themes package.\n';
await writeFile(new URL('palettes.js', dest), generated + 'globalThis.CBOJ_PALETTES = ' + JSON.stringify(palettes, null, 2) + ';\n');
await writeFile(new URL('definitions.js', dest), generated + 'export const definitions = ' + JSON.stringify(definitions, null, 2) + ';\n');
const notices = (await readFile(new URL('NOTICE', source), 'utf8')).replaceAll('\r\n', '\n').split(/^={30,}\n/m);
const selected = notices.filter(block => inputs.some(([, , file]) => block.split('\n')[0].includes(file + '.json')));
if (selected.length !== 6 || !selected.every(block => block.includes('SPDX:    MIT'))) throw Error('Review changed theme license attribution');
await writeFile(new URL('NOTICE.txt', dest), 'Theme color data adapted for Monaco Monarch and the BOJ workspace.\n\n'
  + await readFile(new URL('LICENSE', source), 'utf8') + '\n' + selected.join('\n').trimEnd() + '\n');
